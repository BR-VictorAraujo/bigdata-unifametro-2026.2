    id                                BIGINT PRIMARY KEY,
    cod_concedente                    TEXT,
    cod_financiador                   TEXT,
    cod_gestora                       TEXT,
    cod_orgao                         TEXT,
    cod_secretaria                    TEXT,
    descricao_modalidade              TEXT,
